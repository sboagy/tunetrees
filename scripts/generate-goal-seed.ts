/** Create a NEW seed migration from developer defaults; never rewrite applied SQL. */
import { readFileSync, writeFileSync } from "node:fs";
import { getBuiltInGoals } from "../src/lib/goals/builtins";
import { canonicalJson } from "../src/lib/goals/config";

const [mode, destination] = process.argv.slice(2);
if (
  mode !== "--refresh-current" &&
  (!destination || !["--create", "--check"].includes(mode))
) {
  throw new Error(
    "Usage: tsx scripts/generate-goal-seed.ts --create|--check <migration.sql> or --refresh-current"
  );
}
const literal = (value: string) => `'${value.replaceAll("'", "''")}'`;
const rows = getBuiltInGoals().map((goal) => {
  const scheduler = goal.config.scheduler;
  const technique = scheduler.id === "builtin:fsrs6" ? "fsrs" : "base_interval";
  const intervals =
    scheduler.id === "builtin:interval-ladder"
      ? literal(canonicalJson(scheduler.intervalsDays))
      : "NULL";
  return `  (${[goal.id, goal.name, goal.displayName, goal.description, canonicalJson(goal.config), technique].map(literal).join(", ")}, ${intervals})`;
});
const sql = `-- GENERATED by scripts/generate-goal-seed.ts from src/lib/goals/builtins.ts.
-- Do not edit. After deployment, change defaults through a NEW seed migration.
BEGIN;
SET LOCAL standard_conforming_strings = on;
SET LOCAL tunetrees.goal_seed_write = 'on';
INSERT INTO public.goal (id, name, display_name, description, default_config, default_technique, base_intervals)
VALUES
${rows.join(",\n")}
ON CONFLICT (id) DO UPDATE SET
  display_name = EXCLUDED.display_name,
  description = EXCLUDED.description,
  default_config = EXCLUDED.default_config;
-- Preserve existing last_modified_at. Coordinated cutover requires a full pull.
-- Personal overrides live separately and are never replaced by this seed.
COMMIT;
`;
const currentSeed = "sql_scripts/seed_goal_configuration.sql";
if (mode === "--check") {
  for (const file of [destination, currentSeed]) {
    if (readFileSync(file, "utf8") !== sql) {
      throw new Error(`Goal seed differs from developer defaults: ${file}`);
    }
  }
} else {
  if (mode === "--create") writeFileSync(destination, sql, { flag: "wx" });
  // Reusable trusted restore seed; versioned migration files remain immutable.
  writeFileSync(currentSeed, sql);
}
